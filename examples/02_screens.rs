use appkit::prelude::*;

const PIXEL: &[u8] = &[
    0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A, 0x00, 0x00, 0x00, 0x0D, 0x49, 0x48, 0x44, 0x52, 0x00, 0x00, 0x00,
    0x01, 0x00, 0x00, 0x00, 0x01, 0x08, 0x06, 0x00, 0x00, 0x00, 0x1F, 0x15, 0xC4, 0x89, 0x00, 0x00, 0x00, 0x0D, 0x49,
    0x44, 0x41, 0x54, 0x78, 0x9C, 0x63, 0x00, 0x01, 0x00, 0x00, 0x05, 0x00, 0x01, 0x0D, 0x0A, 0x2D, 0xB4, 0x00, 0x00,
    0x00, 0x00, 0x49, 0x45, 0x4E, 0x44, 0xAE, 0x42, 0x60, 0x82,
];

fn main() -> Result<(), AppKitError> {
    let main_thread = MainThreadMarker::new().expect("an example starts on the main thread");
    for screen in Screen::screens(main_thread) {
        let frame = screen.frame();
        println!(
            "{} (display {:?}): {} x {} points at {}x",
            screen.localized_name(),
            screen.display_id(),
            frame.size.width,
            frame.size.height,
            screen.backing_scale_factor()
        );
    }
    if let Some(screen) = Screen::main(main_thread) {
        println!("main screen: {}", screen.localized_name());
    }
    let image = Image::from_data(PIXEL)?;
    println!("image size: {:?}", image.size());
    println!("empty data: {:?}", Image::from_data(&[]).err());
    Ok(())
}
